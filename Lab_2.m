n = -10:1:10;
x1 = 1*(n==0);
subplot(2,3,1);
stem(n,x1);
xlabel ("sample");
ylabel("amplitude");
title ("Unit impulse");
x2 = 1*(n>=0);
subplot (2,3,2);
stem (n,x2);
xlabel ("sample");
ylabel("amplitude");
title ("Unit step");
x3 = n.*(n>=0);
subplot (2,3,3);
stem (n,x3);
xlabel("samples");
ylabel("amplitude");
title("unit ramp");
x4 = (n.^2)/2 .* (n>=0);
subplot (2,3,4);
stem (n,x4);
xlabel ("sample");
ylabel("amplitude");
title ("Unit parabolic");
x5 = 2*exp(n).*(n>=0);
subplot (2,3,5);
stem (n,x5);
xlabel ("sample");
ylabel("amplitude");
title ("Unit exponential");


x6 = 1*(n>=5);
