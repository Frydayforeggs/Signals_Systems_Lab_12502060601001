clc;
clear all;
close all;
X=[5,-2,-1,4];
xe=(X+X(end:-1:1))/2;
xo=(X-X(end:-1:1))/2;
subplot(1,3,1);
stem(X);
xlabel("sample");
ylabel("amplitude");
title("original signal");
subplot(1,3,2);
stem(xe);
xlabel("sample");
ylabel("amplitude");
title("even component");
subplot(1,3,3);
stem(xo);
xlabel("sample");
ylabel("amplitude");
title("odd component");